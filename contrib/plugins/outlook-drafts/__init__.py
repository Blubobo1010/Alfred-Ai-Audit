"""outlook-drafts: approve, edit or discard every new Outlook draft from Telegram before it is sent.

Registers the ``outlook_draft`` tool (read / update / list pending drafts; it never sends) and the
``plushuman outlook-drafts`` operator command (``install`` writes the button and cron scripts).
The workflow itself lives in :mod:`.drafts`, which the scripts run directly.
"""

from __future__ import annotations

import argparse
import json
import stat
import sys
from pathlib import Path
from typing import Any

from . import drafts

SCRIPT_MARKER = "# outlook-drafts: generated by `plushuman outlook-drafts install`"
# The Telegram adapter's gt:<verb> buttons run these fixed script names (adapter._GT_VERB_DISPATCH).
BUTTON_SCRIPTS = {"gmail-triage/send-draft.sh": "send", "gmail-triage/archive.sh": "discard"}
POLL_SCRIPT = "outlook-drafts-poll.sh"
CRON_JOB_NAME = "outlook-drafts"

TOOL_SCHEMA = {
    "name": "outlook_draft",
    "description": (
        "Read or edit an Outlook draft that is waiting for the owner's approval on Telegram. Every draft "
        "in the mailbox gets a Telegram preview tagged '#REF' with ✅ Invia / 🗑 Scarta buttons. When the "
        "owner replies to such a preview asking for changes, use action='update' with that ref, then tell "
        "them the preview was refreshed and to press ✅ Invia when it looks right. This tool NEVER sends: "
        "only the owner's button sends. 'body' replaces the whole text (formatting and signature included); "
        "read the draft first and keep what should stay."),
    "parameters": {
        "type": "object",
        "properties": {
            "action": {"type": "string", "enum": ["list", "read", "update"]},
            "ref": {"type": "string", "description": "Draft reference from the preview, e.g. 'A7F3K2' or '#A7F3K2'."},
            "subject": {"type": "string"},
            "body": {"type": "string", "description": "New plain-text body (replaces the existing one)."},
            "body_html": {"type": "string", "description": "New HTML body; use instead of 'body' to keep formatting."},
            "to": {"type": "array", "items": {"type": "string"}, "description": "Replaces the To list."},
            "cc": {"type": "array", "items": {"type": "string"}, "description": "Replaces the Cc list."},
            "bcc": {"type": "array", "items": {"type": "string"}, "description": "Replaces the Bcc list."},
        },
        "required": ["action"],
    },
}


def _tool_handler(args: dict[str, Any], **_: Any) -> str:
    action = str(args.get("action") or "")
    try:
        service = drafts.Drafts.from_runtime()
        if action == "list":
            return json.dumps({"pending": service.list_pending()})
        ref = str(args.get("ref") or "")
        if not ref:
            return json.dumps({"error": "ref is required for read and update"})
        if action == "read":
            return json.dumps(service.read(ref), ensure_ascii=False)
        if action == "update":
            fields = {k: args.get(k) for k in ("subject", "body", "body_html", "to", "cc", "bcc") if args.get(k) is not None}
            return json.dumps(service.update(ref, **fields))
        return json.dumps({"error": f"unknown action {action!r}"})
    except drafts.DraftsError as exc:
        return json.dumps({"error": str(exc)})


def _tool_available() -> bool:
    try:
        drafts.load_settings()
    except drafts.DraftsError:
        return False
    return all(drafts.read_secret(n) for n in ("MSGRAPH_TENANT_ID", "MSGRAPH_CLIENT_ID", "MSGRAPH_CLIENT_SECRET"))


# ------------------------------------------------------------------------------------------- install


def _script_text(command: str, home: Path) -> str:
    import hermes_constants
    core_root = Path(hermes_constants.__file__).resolve().parent
    module = Path(drafts.__file__).resolve()
    extra = ' "$1"' if command in ("send", "discard") else ""
    return (f"#!/usr/bin/env bash\n{SCRIPT_MARKER}\nset -euo pipefail\n"
            f"export HERMES_HOME={_sh(str(home))}\n"
            f"export PYTHONPATH={_sh(str(core_root))}\"${{PYTHONPATH:+:$PYTHONPATH}}\"\n"
            f"exec {_sh(sys.executable)} {_sh(str(module))} {command}{extra}\n")


def _sh(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"


def install_scripts(home: Path, *, force: bool = False) -> list[Path]:
    """Write the two button scripts and the poll script; refuse to clobber scripts this plugin did not write."""
    targets = {**{home / "scripts" / rel: cmd for rel, cmd in BUTTON_SCRIPTS.items()},
               home / "scripts" / POLL_SCRIPT: "poll"}
    foreign = [p for p in targets if p.exists() and SCRIPT_MARKER not in p.read_text(encoding="utf-8-sig", errors="replace")]
    if foreign and not force:
        raise drafts.DraftsError("refusing to overwrite existing scripts (use --force): "
                                 + ", ".join(str(p) for p in foreign))
    for path, command in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_script_text(command, home), encoding="utf-8")
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IRUSR)
    return sorted(targets)


def _setup_cli(subparser: argparse.ArgumentParser) -> None:
    subs = subparser.add_subparsers(dest="outlook_drafts_action")
    install = subs.add_parser("install", help="Write the Telegram button scripts and the poll script")
    install.add_argument("--force", action="store_true", help="Overwrite existing gmail-triage scripts")
    subs.add_parser("poll", help="Check the Drafts folder once")
    for name in ("send", "discard"):
        subs.add_parser(name).add_argument("ref")
    subs.add_parser("status", help="Show tracked drafts by status")
    subparser.set_defaults(func=_cli_command)


def _cli_command(args: argparse.Namespace) -> int:
    action = getattr(args, "outlook_drafts_action", None)
    if action == "install":
        try:
            drafts.load_settings()
            paths = install_scripts(drafts.hermes_home(), force=args.force)
        except drafts.DraftsError as exc:
            print(str(exc), file=sys.stderr)
            return 1
        print("Wrote:\n  " + "\n  ".join(str(p) for p in paths))
        print("\nNow schedule the poll (every minute, no LLM, errors to Telegram):\n"
              f"  plushuman cron create 'every 1m' --name {CRON_JOB_NAME} --script {POLL_SCRIPT} "
              "--no-agent --deliver telegram")
        return 0
    if action in ("poll", "send", "discard", "status"):
        return drafts.run_command([action] + ([args.ref] if action in ("send", "discard") else []))
    print("Usage: plushuman outlook-drafts {install|poll|send|discard|status}")
    return 2


def register(ctx) -> None:
    ctx.register_tool(name="outlook_draft", toolset="outlook_drafts", schema=TOOL_SCHEMA, handler=_tool_handler,
                      check_fn=_tool_available, description=TOOL_SCHEMA["description"], emoji="📝")
    ctx.register_cli_command(name="outlook-drafts", help="Approve Outlook drafts from Telegram",
                             setup_fn=_setup_cli, handler_fn=_cli_command,
                             description="Every new Outlook draft waits for ✅ Invia / 🗑 Scarta on Telegram.")
